// Turns the name into signature paths (src/content/signature.ts), one filled
// path per letter, in Mrs Saint Delafield (SIL OFL 1.1), so the hero can
// write it out letter by letter with no font download.
// Run with `npm run signature`, then commit src/content/signature.ts.
import opentype from 'opentype.js'
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url))
const NAME = 'Rohan Reddy Bandi'
const SIZE = 100 // font units → px at this size; the SVG scales anyway

const cache = root('node_modules/.cache/sig')
const file = `${cache}/MrsSaintDelafield-Regular.ttf`
if (!existsSync(file)) {
  mkdirSync(cache, { recursive: true })
  execFileSync('curl', [
    '-fsSL',
    'https://raw.githubusercontent.com/google/fonts/main/ofl/mrssaintdelafield/MrsSaintDelafield-Regular.ttf',
    '-o',
    file,
  ])
}
const buf = readFileSync(file)
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))

const round = (n) => Math.round(n * 10) / 10
// Word by word, with a wider gap than the font's own space, so the three
// names don't run together
const GAP = 22
const layout = (x, y) =>
  NAME.split(' ').flatMap((word) => {
    const paths = font.getPaths(word, x, y, SIZE, { kerning: true }).map((p, i) => Object.assign(p, { ch: word[i] }))
    x += font.getAdvanceWidth(word, SIZE, { kerning: true }) + GAP
    return paths
  })
// opentype.js 2's own toPathData drops parts of these glyphs, so write the
// path data out by hand
const toD = (path) =>
  path.commands
    .map((c) => {
      const pt = (x, y) => `${round(x)} ${round(y)}`
      if (c.type === 'M' || c.type === 'L') return c.type + pt(c.x, c.y)
      if (c.type === 'Q') return `Q${pt(c.x1, c.y1)} ${pt(c.x, c.y)}`
      if (c.type === 'C') return `C${pt(c.x1, c.y1)} ${pt(c.x2, c.y2)} ${pt(c.x, c.y)}`
      return 'Z'
    })
    .join('')

// Measure, then lay out again shifted so the ink starts at 0,0 (plus a
// little room)
const pad = 4
let box = { x1: Infinity, y1: Infinity, x2: -Infinity, y2: -Infinity }
for (const p of layout(0, SIZE)) {
  const b = p.getBoundingBox()
  box = { x1: Math.min(box.x1, b.x1), y1: Math.min(box.y1, b.y1), x2: Math.max(box.x2, b.x2), y2: Math.max(box.y2, b.y2) }
}
const letters = layout(pad - box.x1, SIZE + pad - box.y1).map((p) => {
  const b = p.getBoundingBox()
  return { ch: p.ch, d: toD(p), x1: round(b.x1), x2: round(b.x2) }
})
const w = round(box.x2 - box.x1 + pad * 2)
const h = round(box.y2 - box.y1 + pad * 2)

const out = `// Generated by scripts/make-signature.mjs from Mrs Saint Delafield
// (SIL OFL 1.1). Don't edit; re-run \`npm run signature\`.

export const signature = {
  width: ${w},
  height: ${h},
  letters: [
${letters.map((l) => `    { ch: ${JSON.stringify(l.ch)}, x1: ${l.x1}, x2: ${l.x2}, d: '${l.d}' },`).join('\n')}
  ],
}
`
writeFileSync(root('src/content/signature.ts'), out)
console.log(`signature: ${letters.length} letters, ${w}×${h}`)
